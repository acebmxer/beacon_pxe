#!/bin/sh
# Start a kernel NFS server that exports /nfs (read-only) to PXE clients.
# NFSv3 is used because that is what the distro initramfs network mounter
# (klibc nfsmount) speaks, so rpcbind + rpc.mountd must be running too.
#
# The export is limited to the subnet(s) of the boot interface set in Server
# Settings. The web app writes that interface into the generated dnsmasq.conf
# (interface=...), which this container reads from the shared dnsmasqconf
# volume. It is re-checked every few seconds, so changing the boot interface
# (or its address) re-exports without restarting this container.
set -eu

TEMPLATE=/etc/beacon/exports.template
CONF_DIR=/dnsmasq
CONF="$CONF_DIR/dnsmasq.conf"

# The nfsd/nfs modules live on the host; load them if not already present
# (harmless if they are built-in or already loaded).
modprobe nfs 2>/dev/null || true
modprobe nfsd 2>/dev/null || true

# nfsd's control filesystem.
mount -t nfsd nfsd /proc/fs/nfsd 2>/dev/null || true

# Who may mount /nfs, as a space-separated list ("" = nobody).
#   - dnsmasqconf not mounted (a docker-compose.yml from before this change):
#     every address, as before, with a note in the log.
#   - no interface= line (boot interface left blank, so dnsmasq also listens
#     everywhere): every address.
#   - otherwise: each IPv4 subnet on that interface. An interface with no IPv4
#     address exports to nobody; dnsmasq can't boot clients there either.
allowed_clients() {
  if [ ! -d "$CONF_DIR" ]; then
    echo "*"
    return 0
  fi
  iface=$(sed -n 's/^interface=//p' "$CONF" 2>/dev/null | head -n 1)
  if [ -z "$iface" ]; then
    echo "*"
    return 0
  fi
  out=""
  for cidr in $(ip -4 -o addr show dev "$iface" 2>/dev/null | awk '{print $4}'); do
    eval "$(ipcalc -n -p "$cidr")"
    out="$out $NETWORK/$PREFIX"
  done
  echo "${out# }"
}

describe() {
  if [ "$1" = "*" ] && [ ! -d "$CONF_DIR" ]; then
    echo "every address (this docker-compose.yml doesn't share the dnsmasq config with nfs; use the current one to limit NFS to the boot LAN)"
  elif [ "$1" = "*" ]; then
    echo "every address (no boot interface set)"
  elif [ -z "$1" ]; then
    echo "nobody (the boot interface has no IPv4 address)"
  else
    echo "$1"
  fi
}

# Write /etc/exports from the template's options, one entry per client.
write_exports() {
  opts=$(sed -n 's|^/nfs \*(\(.*\))$|\1|p' "$TEMPLATE")
  line="/nfs"
  # `*` is a client spec here, not a file pattern.
  set -f
  for c in $1; do
    line="$line $c($opts)"
  done
  set +f
  echo "# Generated by entrypoint.sh from $TEMPLATE; do not edit." > /etc/exports
  if [ -n "$1" ]; then
    echo "$line" >> /etc/exports
  fi
}

# A fresh install starts before the web app has written its first config; wait
# for it rather than exporting to every address in the meantime.
trap 'exit 0' TERM INT
if [ -d "$CONF_DIR" ]; then
  n=0
  while [ ! -f "$CONF" ]; do
    if [ $((n % 20)) -eq 0 ]; then
      echo "[nfs] waiting for $CONF from the web app"
    fi
    n=$((n + 1))
    sleep 3 & wait $! || true
  done
fi

# rpcbind (portmapper) is required for NFSv3.
rpcbind || true

# mountd is pinned to a fixed port so it can be firewalled. Left unpinned it
# binds an ephemeral port that changes on every restart, which makes the server
# impossible to put behind a host firewall: the mount RPC lands on a different
# port each boot and gets dropped. Clients find it via rpcbind either way.
#
# With a host firewall (this container uses host networking, so its traffic hits
# the host INPUT chain), open on the boot interface:
#     111/tcp+udp   rpcbind
#     2049/tcp      nfsd
#     20048/tcp     rpc.mountd (below)
MOUNTD_PORT="${MOUNTD_PORT:-20048}"

# Publish the exports and start the daemons.
CLIENTS=$(allowed_clients)
write_exports "$CLIENTS"
echo "[nfs] exporting /nfs to $(describe "$CLIENTS")"
exportfs -rv
rpc.mountd --no-udp -p "$MOUNTD_PORT"
rpc.nfsd --no-udp 8

echo "[nfs] server up (mountd on port $MOUNTD_PORT); current exports:"
exportfs -v

shutdown() {
  echo "[nfs] shutting down"
  rpc.nfsd 0 || true
  exportfs -ua || true
  exit 0
}
trap shutdown TERM INT

# rpc.nfsd backgrounds its kernel threads, so hold the container open, and
# follow boot-interface changes meanwhile.
while true; do
  sleep 5 & wait $! || true
  NOW=$(allowed_clients)
  if [ "$NOW" != "$CLIENTS" ]; then
    CLIENTS="$NOW"
    write_exports "$CLIENTS"
    echo "[nfs] boot interface changed; exporting /nfs to $(describe "$CLIENTS")"
    exportfs -ra || echo "[nfs] exportfs failed"
  fi
done
